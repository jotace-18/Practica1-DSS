package com.example.demo.service;

import java.util.List;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import com.example.demo.model.Producto;
import com.example.demo.repository.ProductoRepo;

@Service
public class DatabaseExportService {

    @Autowired
    private ProductoRepo productoRepo;

    public String exportDatabaseToSql() {
        StringBuilder sql = new StringBuilder();
        List<Producto> products = productoRepo.findAll();

        sql.append("CREATE TABLE IF NOT EXISTS producto (\n");
        sql.append("    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n");
        sql.append("    name VARCHAR(255),\n");
        sql.append("    price DOUBLE PRECISION NOT NULL\n");
        sql.append(");\n\n");

        for (Producto product : products) {
            String name = product.getName() == null
                    ? "NULL" : "'" + product.getName().replace("'", "''") + "'";

            sql.append("INSERT INTO producto (id, name, price) VALUES (");
            sql.append(product.getId());
            sql.append(", ");
            sql.append(name);
            sql.append(", ");
            sql.append(product.getPrice());
            sql.append(");\n");
        }

        return sql.toString();
    }
}
